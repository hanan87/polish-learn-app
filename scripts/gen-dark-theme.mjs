// Generates src/dark.css: a dark palette expressed as overrides of Tailwind's color variables,
// so every existing utility (bg-slate-50, text-amber-900, ring-rose-200…) adapts without per-component dark: classes.
//   - slate is inverted (light surfaces become dark, dark text becomes light)
//   - tinted backgrounds (50/100/200) become deep tints of the hue mixed into the dark base
//   - dark text shades (700–950) become light shades; 300 rings become mid-dark
//   - 400–600 (buttons, accents) stay as they are
import { readFileSync, writeFileSync } from 'node:fs';

const theme = readFileSync('node_modules/tailwindcss/theme.css', 'utf8');
const color = (name, shade) => {
  const m = theme.match(new RegExp(`--color-${name}-${shade}:\\s*([^;]+);`));
  if (!m) throw new Error(`missing ${name}-${shade}`);
  return m[1].trim();
};

const BASE = 'oklch(17% 0.02 262)';
const lines = [];

// Slate: inverted scale.
const slateMap = {
  50: 'oklch(15.5% 0.02 262)',
  100: 'oklch(21% 0.025 262)',
  200: 'oklch(29% 0.03 262)',
  300: color('slate', 600),
  400: color('slate', 500),
  500: color('slate', 400),
  600: color('slate', 300),
  700: color('slate', 200),
  800: color('slate', 100),
  900: color('slate', 50),
  950: 'oklch(99% 0 0)',
};
for (const [shade, value] of Object.entries(slateMap)) lines.push(`  --color-slate-${shade}: ${value};`);

const hues = ['rose', 'amber', 'emerald', 'sky', 'indigo', 'violet', 'orange', 'red', 'teal', 'green', 'yellow', 'pink', 'blue', 'cyan', 'purple', 'lime', 'fuchsia'];
for (const h of hues) {
  const mid = color(h, 500);
  lines.push(`  --color-${h}-50: color-mix(in oklab, ${mid} 13%, ${BASE});`);
  lines.push(`  --color-${h}-100: color-mix(in oklab, ${mid} 22%, ${BASE});`);
  lines.push(`  --color-${h}-200: color-mix(in oklab, ${mid} 38%, ${BASE});`);
  lines.push(`  --color-${h}-300: color-mix(in oklab, ${mid} 55%, ${BASE});`);
  lines.push(`  --color-${h}-700: ${color(h, 300)};`);
  lines.push(`  --color-${h}-800: ${color(h, 200)};`);
  lines.push(`  --color-${h}-900: ${color(h, 100)};`);
  lines.push(`  --color-${h}-950: ${color(h, 50)};`);
}

const css = `/* Generated by scripts/gen-dark-theme.mjs – do not edit by hand. */
.dark {
  color-scheme: dark;
  --surface: oklch(21% 0.025 262);
${lines.join('\n')}
}
`;
writeFileSync('src/dark.css', css);
console.log(`src/dark.css written (${lines.length} variables)`);
